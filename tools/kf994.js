/* 994 — **«태생 α 램프» 를 되돌린 사본 키프레임**을 제품에서 **파생**한다(자 넷이 같이 읽는다).
 *
 *   const { kfPre994 } = require('./kf994');
 *   const KF = kfPre994();            // 없으면 null
 *   … page 안에서 <style> 로 넣고 **스폰 전에** 걸어야 한다(키프레임은 애니가 붙을 때 굳는다)
 *
 * ── 왜 필요한가 ───────────────────────────────────────────────────────────
 * 994 가 알의 태생 세기를 «아이콘과 겹쳐 있는 창» 에 맞추면서(0% `.10` → 10% `.55`),
 * **태생 프레임에서 알이 라벨을 씻는 일이 거의 사라졌다.** 그런데 683 계열의 자 넷은 그 씻김을
 * **전제**로 묻는 절을 갖고 있다:
 *   · `probe683d` [2]·[3] — «패치 위를 알이 다시 덮는다»(11회차 판의 물음)
 *   · `probe683c` [3-a]   — «795 의 패치가 듣고 있다»(패치를 걷으면 씻김이 돌아온다)
 *   · `probe683e` 전부     — 14회차 «극성» 진단(BASE ↔ SCREEN ↔ FLIP 을 태생 프레임에서 견준다)
 *   · `verify753` [B2]~    — 알 잉크의 **기하**(중심·전경 몫). 세기가 낮으면 잉크 추출이 얇아져
 *                            반픽셀 격자 위에서 값이 튄다(묻는 것은 기하이지 세기가 아니다)
 * 그 절들은 **그 물음이 사는 나무**(994 이전)에서 재야 뜻이 그대로다 — `probe683d` [4] 가
 * 12·13회차 제품을 `NOFADE` 로 되돌리고 «11회차 판에서 알이 남긴 몫» 을 지키는 것과 같은 꼴이다.
 * ⚠ 문턱은 어느 자에서도 한 칸도 안 넓혔다(333 처방 — 재는 나무만 옮겼다).
 *
 * ── 왜 손으로 안 적는가 ───────────────────────────────────────────────────
 * 같은 곡선을 자 넷에 베껴 적으면 **표가 다섯 벌**이 된다(402 «사본을 지운다»). 여기서는 제품의
 * `@keyframes fxRlic` 를 읽어 ① 램프 키프레임을 지우고 ② `0%` 의 α 를 **그 램프가 적은 봉우리 값**
 * 으로 되돌린다 — 봉우리(.55 · 753 9회차 2인 독립 일치)를 나중에 누가 옮겨도 사본이 따라온다.
 * 램프가 없으면(= 994 이전 트리) 곡선을 **그대로** 돌려주므로 «수리 전 사본» 대조가 그대로 돈다.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const SRC = path.resolve(__dirname, '..', 'index.html');

function kfPre994(code) {
  let src = code;
  if (!src) { try { src = fs.readFileSync(SRC, 'utf8'); } catch (_) { return null; } }
  const m = src.match(/@keyframes fxRlic\{[\s\S]*?\}\}/);
  if (!m) return null;
  let kf = m[0].replace(/\s+/g, ' ');
  /* 램프 = «opacity 만 적은» 중간 키프레임 하나(0%·35%·100% 은 transform 을 같이 적는다) */
  const ramp = kf.match(/\s*\d+%\{opacity:([.\d]+)\}/);
  if (!ramp) return kf;                       /* 994 이전 트리 — 되돌릴 것이 없다 */
  kf = kf.replace(ramp[0], '');
  kf = kf.replace(/(0%\{[^{}]*opacity:)[.\d]+(\})/, '$1' + ramp[1] + '$2');
  return kf;
}

module.exports = { kfPre994, SRC };
