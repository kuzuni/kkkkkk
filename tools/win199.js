/* 199 33회차 — «창 역량»(observation-window competence) 한 곳
 *
 *   const W = require('./win199');
 *   W.ladderSw(run)                 사다리 문턱 스테이지(제품 `eBandSw`) — 없으면 null
 *   W.lateWalls(assignedWalls, sw)  문턱 «위» 의 배정 벽 개수(잘린 정체는 호출부가 이미 뺀 것)
 *   W.judge({ sw, late })           그 창이 말미 축을 판정할 수 있는가
 *
 * ── 왜 이 자가 필요한가 (32-4 가 실측으로 찍은 자리) ─────────────────────
 * 32회차가 밴드 사다리(`ES_BAND` 40 → 문턱 위 `ES_BAND2` 16)를 제품에 얹고 30일 표를 봤더니
 * ①(벽 시각)·③(성장 체감)이 **비트 동일**이고 진행만 −2.8% 였다. 30일 표만 읽으면 그 변경은
 * «순수한 손해» 라 **되돌림이 답**이 된다. 그런데 90일 표에서는 같은 손잡이가 ① 간격 오차를
 * −18.7% → **−3.2%** 로 줄이고 ② 말미 수급을 **+7.7%** 올린다(32-5).
 *
 * 뿌리는 손잡이가 아니라 **창**이다 — 30일 부지런의 끝이 s376 이고 사다리의 첫 좁은 관문이
 * 바로 그 s376 이다. 간격은 벽이 **둘 이상**이어야 정의되고, 창 끝의 벽은 잘린 벽(`trunc`)이라
 * 배정에서 빠진다 ⇒ 30일 창이 재는 벽은 전부 문턱 **아래**, 즉 사다리가 한 글자도 안 건드린
 * 자리다. 그 창의 수는 «판정» 이 아니라 **그림자**다.
 *
 * ⚑ 그래서 이 자는 «값이 나쁘다» 를 말하지 않는다. **«이 창은 이 축을 못 본다»** 를 말한다.
 * 표가 스스로 그 말을 못 하면, 다음 회차는 32-4 를 다시 겪고 이번에는 되돌린다.
 *
 * ── 판정식 ───────────────────────────────────────────────────────────────
 * 말미 축(① 문턱 위 간격·적중 · ③ 문턱 위 진폭 · ② 말미 한계 수급) 판정 가능
 *   ⇔ 문턱 위에서 **잘리지 않은 배정 벽이 p50 로 2개 이상**.
 * 2 인 이유는 임의의 여유가 아니라 **간격의 정의**다(벽 하나로는 간격이 없다 — 13회차 JJ 가
 * `spanOf` 에 «배정 벽 2개 미만 = 미정의» 를 못박은 그 수와 같은 수다).
 */
'use strict';

/* 간격이 정의되는 최소 벽 수 — 자의적 여유가 아니라 «간격 = 벽과 벽 사이» 의 정의 그대로. */
const MIN_LATE = 2;

/* 문턱 = **첫 «좁은» 관문**이다 — 제품 상수 `eBandSw`(= 360) 그 자체가 아니다.
   ⚠ 이 한 칸이 판정을 바꾼다: s360 은 **두 격자의 공통 앵커**라(32-3 — 상수 40 표에도 사다리
   표에도 같은 자리에 선다) 그 벽은 사다리가 만든 벽이 아니다. 그것을 «말미 벽» 으로 세면
   30일 창이 벽 1개를 갖고 «반쯤 본다» 가 되어, 못 보는 창이 판정 가능으로 새어 나간다.
   ⇒ 문턱 = `eBandSw + ES_BAND2`(= 376 = 첫 좁은 관문).
   실행이 상수를 실어 주면 그것으로 세고(33회차 이후), 못 실은 옛 표(JSON 리플레이)는
   **관문 격자에서 되찾는다** — 간격이 처음 달라진 **뒤**의 칸이 곧 첫 좁은 관문이다.
   간격이 끝까지 일정하면 사다리가 없는 것이므로 **null**(«말미 축 자체가 없다»)이다. */
function ladderSw(r) {
  if (!r || typeof r !== 'object') return null;
  const sw = r.bandSw, b2 = r.band2, b = r.band;
  /* 폭이 안 좁아지면(되돌림본 `ES_BAND2 = ES_BAND`) 사다리가 아니다 — 수를 내면 안 된다. */
  if (sw > 0 && b2 > 0 && b > 0) return b2 < b ? sw + b2 : null;
  const g = Array.isArray(r.gateSet) ? r.gateSet : null;
  if (!g || g.length < 3) return null;
  const w0 = g[1] - g[0];
  for (let i = 1; i + 1 < g.length; i++) {
    if (g[i + 1] - g[i] !== w0) return g[i + 1];   /* 폭이 처음 달라진 뒤의 첫 칸 = 좁은 구간의 첫 관문 */
  }
  return null;
}

/* 문턱 «위» 의 벽 개수. 호출부가 이미 «배정 벽»(관문 정체 · 잘린 정체 제외)만 넘긴다 —
   여기서 다시 거르면 자가 둘이 되고, 둘이 갈리는 날 본문이 고르게 된다(20회차 규약). */
function lateWalls(walls, sw) {
  if (!Array.isArray(walls) || !(sw > 0)) return 0;
  return walls.filter(w => w && typeof w.stage === 'number' && w.stage >= sw).length;
}

/* 판정. `can === null` 은 «못 본다» 가 아니라 «볼 것이 없다»(사다리 없음)다 — 둘을 같은
   말로 적으면 사다리를 지운 되돌림본이 «판정 불가» 로 읽혀 조용히 통과한다. */
function judge(o) {
  const sw = o && o.sw, late = (o && o.late) | 0;
  if (!(sw > 0)) return { can: null, late, why: '사다리 없음 — 밴드가 상수라 말미 축 자체가 없다' };
  if (late >= MIN_LATE) return { can: true, late, why: `문턱 s${sw} 위 배정 벽 ${late}개 ≥ ${MIN_LATE}` };
  if (late === 1) return { can: false, late, why: `문턱 s${sw} 위 배정 벽 1개 — 간격은 벽이 둘 이상이어야 정의된다` };
  return { can: false, late, why: `문턱 s${sw} 위 배정 벽 0개 — 이 창은 문턱 위를 한 칸도 완주하지 않는다` };
}

/* 표에 그대로 실을 한 마디(자가 말하게 — 본문이 손으로 옮겨 적지 않게).
   ⚠ 33회차 정정 — 초판은 «90일 표로 읽어라» 라고 **창의 이름을 박아** 뒀는데, 그 자리에서
   90일 창을 재 보니 부지런 말미 벽이 **1개**(s392 정체는 창 끝이라 잘린다)라 90일도 이 자에
   걸린다(33-3). 자가 아직 못 재 본 창을 처방으로 박으면 그 처방이 곧 다음 회차의 «헛초록» 이
   된다 — 자는 **필요 조건**만 말하고, 어느 창이 그 조건을 만족하는지는 실측이 정한다. */
function label(v) {
  if (!v) return '—';
  if (v.can === null) return `**해당 없음** (${v.why})`;
  return v.can ? `**판정 가능** (${v.why})`
               : `⚠ **판정 불가 — 문턱 위 배정 벽 ${MIN_LATE}개를 담는 더 긴 창으로 읽어라** (${v.why})`;
}

module.exports = { MIN_LATE, ladderSw, lateWalls, judge, label };
